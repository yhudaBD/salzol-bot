function passes(result, want) {
  var toks = S.tokenize(result.name + " " + (result.brand || ""));   // היצרן נחשב: "קוטג' 9%" [תנובה]
  return want.every(function (w) {
    var nw = S.tokenize(w)[0];
    return toks.some(function (t) { return t.indexOf(nw) === 0; });
  });
}

function main() {
  var verbose = process.argv.indexOf("-v") >= 0;
  var file = path.join(__dirname, "docs", "prices.json");
  var data = JSON.parse(fs.readFileSync(file, "utf8"));
  var t0 = Date.now();
  var index = S.buildIndex(data.items);
  console.log("אינדקס: %d מוצרים (%d ms)", index.length, Date.now() - t0);

  var ok = 0, failures = [], times = [];
  CASES.forEach(function (c) {
    var t = Date.now();
    var res = S.search(index, c[0], 5);
    times.push(Date.now() - t);
    var pass = res.slice(0, 2).some(function (r) { return passes(r, c[1]); });
    if (pass) ok++;
    else failures.push([c, res]);
    if (verbose || !pass) {
      console.log("%s  %s", pass ? "OK  " : "FAIL", c[0]);
      res.slice(0, 3).forEach(function (r) {
        console.log("        %s  %s  %s", r.score.toFixed(2), r.name, JSON.stringify(r.prices));
      });
    }
  });

  var pct = 100 * ok / CASES.length;
  times.sort(function (a, b) { return a - b; });
  console.log("\nעברו %d מתוך %d (%s%%). יעד: 90%%", ok, CASES.length, pct.toFixed(0));
  console.log("זמן חיפוש: חציון %d ms, מקסימום %d ms", times[times.length >> 1], times[times.length - 1]);
  process.exit(pct >= 90 ? 0 : 1);
}

main();
